package io.github.leogan.kiln.gen;

import io.github.leogan.kiln.Schema;
import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Set;
import java.util.TreeMap;

/** Emits Java structs with {@code encodedSize}, {@code encode}, and {@code decode}. */
public final class JavaGen {
    private static final Set<String> KEYWORDS = Set.of(
            "abstract", "assert", "boolean", "break", "byte", "case", "catch", "char", "class", "const",
            "continue", "default", "do", "double", "else", "enum", "extends", "final", "finally", "float",
            "for", "goto", "if", "implements", "import", "instanceof", "int", "interface", "long", "native",
            "new", "package", "private", "protected", "public", "return", "short", "static", "strictfp",
            "super", "switch", "synchronized", "this", "throw", "throws", "transient", "try", "void",
            "volatile", "while", "var", "record", "yield", "sealed", "permits", "true", "false", "null");

    private JavaGen() {}

    public static TreeMap<String, String> emit(Schema root, String pkg) {
        List<Schema> order = new ArrayList<>();
        walk(root, new LinkedHashSet<>(), order);
        TreeMap<String, String> files = new TreeMap<>();
        if (order.isEmpty()) {
            if (root.kind != Schema.Kind.DICT) {
                throw new IllegalArgumentException("generator root must be a struct or dict");
            }
            String name = className(root.name == null || root.name.isEmpty() ? "Root" : root.name);
            files.put(name, emitDictClass(pkg, name, root));
            return files;
        }
        for (Schema schema : order) {
            String name = className(schema.name);
            files.put(name, emitStruct(pkg, name, schema));
        }
        return files;
    }

    private static void walk(Schema schema, LinkedHashSet<Schema> seen, List<Schema> order) {
        if (schema == null) {
            return;
        }
        switch (schema.kind) {
            case LIST, OPT, DICT -> walk(schema.elem, seen, order);
            case STRUCT -> {
                if (!seen.add(schema)) {
                    return;
                }
                for (Schema.Field field : schema.fields()) {
                    walk(field.type, seen, order);
                }
                order.add(schema);
            }
            default -> {
            }
        }
    }

    private static String emitStruct(String pkg, String className, Schema schema) {
        Src src = new Src();
        boolean lists = uses(schema, Schema.Kind.LIST);
        boolean dicts = uses(schema, Schema.Kind.DICT);
        boolean kilnex = dicts;
        src.line("// Generated by gld-kilngen-java. Do not edit.");
        src.line("package " + pkg + ";");
        src.line("");
        src.line("import io.github.leogan.kiln.Wire;");
        if (kilnex) {
            src.line("import io.github.leogan.kiln.KilnException;");
        }
        if (lists || dicts) {
            src.line("import java.util.ArrayList;");
        }
        if (lists) {
            src.line("import java.util.List;");
        }
        if (dicts) {
            src.line("import java.util.LinkedHashMap;");
            src.line("import java.util.Map;");
        }
        src.line("");
        src.line("public final class " + className + " {");
        src.indent++;
        for (Schema.Field field : schema.fields()) {
            src.line("public " + fieldType(field.type) + " " + fieldName(field.name) + ";");
        }
        src.line("");
        src.line("public " + className + "() {");
        src.line("}");
        src.line("");
        src.line("public int encodedSize() {");
        src.indent++;
        src.line("int n = 0;");
        for (Schema.Field field : schema.fields()) {
            sizeOf(src, field.type, "this." + fieldName(field.name), 0);
        }
        src.line("return n;");
        src.indent--;
        src.line("}");
        src.line("");
        src.line("public byte[] encode() {");
        src.indent++;
        src.line("byte[] out = new byte[encodedSize()];");
        src.line("encodeTo(out, 0);");
        src.line("return out;");
        src.indent--;
        src.line("}");
        src.line("");
        src.line("public int encodeTo(byte[] out, int offset) {");
        src.indent++;
        src.line("int o = offset;");
        for (Schema.Field field : schema.fields()) {
            writeOf(src, field.type, "this." + fieldName(field.name), 0);
        }
        src.line("return o;");
        src.indent--;
        src.line("}");
        src.line("");
        src.line("public static " + className + " decode(byte[] data) {");
        src.indent++;
        src.line("return decode(data, 0, data.length);");
        src.indent--;
        src.line("}");
        src.line("");
        src.line("public static " + className + " decode(byte[] data, int offset, int length) {");
        src.indent++;
        src.line("Wire.In in = new Wire.In(data, offset, offset + length, Wire.DEFAULT_CAP, false);");
        src.line(className + " value = decodeFrom(in);");
        src.line("in.finish();");
        src.line("return value;");
        src.indent--;
        src.line("}");
        src.line("");
        src.line("public static " + className + " decodeFrom(Wire.In in) {");
        src.indent++;
        src.line(className + " value = new " + className + "();");
        for (Schema.Field field : schema.fields()) {
            readOf(src, field.type, "value." + fieldName(field.name), 0);
        }
        src.line("return value;");
        src.indent--;
        src.line("}");
        src.indent--;
        src.line("}");
        return src.sb.toString();
    }

    private static String emitDictClass(String pkg, String className, Schema schema) {
        Src src = new Src();
        src.line("// Generated by gld-kilngen-java. Do not edit.");
        src.line("package " + pkg + ";");
        src.line("");
        src.line("import io.github.leogan.kiln.KilnException;");
        src.line("import io.github.leogan.kiln.Wire;");
        src.line("import java.util.ArrayList;");
        src.line("import java.util.LinkedHashMap;");
        src.line("import java.util.Map;");
        src.line("");
        src.line("public final class " + className + " {");
        src.indent++;
        src.line("public " + fieldType(schema) + " values;");
        src.line("");
        src.line("public " + className + "() {");
        src.line("}");
        src.line("");
        src.line("public int encodedSize() {");
        src.indent++;
        src.line("int n = 0;");
        sizeOf(src, schema, "this.values", 0);
        src.line("return n;");
        src.indent--;
        src.line("}");
        src.line("");
        src.line("public byte[] encode() {");
        src.indent++;
        src.line("byte[] out = new byte[encodedSize()];");
        src.line("encodeTo(out, 0);");
        src.line("return out;");
        src.indent--;
        src.line("}");
        src.line("");
        src.line("public int encodeTo(byte[] out, int offset) {");
        src.indent++;
        src.line("int o = offset;");
        writeOf(src, schema, "this.values", 0);
        src.line("return o;");
        src.indent--;
        src.line("}");
        src.line("");
        src.line("public static " + className + " decode(byte[] data) {");
        src.indent++;
        src.line("Wire.In in = Wire.In.of(data);");
        src.line(className + " value = new " + className + "();");
        readOf(src, schema, "value.values", 0);
        src.line("in.finish();");
        src.line("return value;");
        src.indent--;
        src.line("}");
        src.indent--;
        src.line("}");
        return src.sb.toString();
    }

    private static boolean uses(Schema schema, Schema.Kind kind) {
        if (schema.kind == kind) {
            return true;
        }
        if (schema.elem != null && uses(schema.elem, kind)) {
            return true;
        }
        if (schema.kind == Schema.Kind.STRUCT) {
            for (Schema.Field field : schema.fields()) {
                if (uses(field.type, kind)) {
                    return true;
                }
            }
        }
        return false;
    }

    private static void sizeOf(Src src, Schema type, String expr, int depth) {
        if (type.kind == Schema.Kind.OPT) {
            src.line("n += 1;");
            src.line("if (" + expr + " != null) {");
            src.indent++;
            sizeOf(src, type.elem, expr, depth);
            src.indent--;
            src.line("}");
            return;
        }
        switch (type.kind) {
            case BOOL, I8, U8 -> src.line("n += 1;");
            case I16, U16 -> src.line("n += 2;");
            case I32, U32, F32 -> src.line("n += 4;");
            case I64, INT, U64, UINT, F64 -> src.line("n += 8;");
            case STR -> src.line("n += 4 + Wire.utf8Length(" + expr + ");");
            case BYTES -> src.line("n += 4 + " + expr + ".length;");
            case STRUCT -> src.line("n += " + expr + ".encodedSize();");
            case LIST -> {
                if (rawByteList(type)) {
                    src.line("n += 4 + " + expr + ".length;");
                } else if (type.elem.fixedWidth() >= 0) {
                    src.line("n += 4 + " + expr + ".size() * " + type.elem.fixedWidth() + ";");
                } else {
                    String item = src.fresh("item");
                    src.line("n += 4;");
                    src.line("for (" + fieldType(type.elem) + " " + item + " : " + expr + ") {");
                    src.indent++;
                    sizeOf(src, type.elem, item, depth + 1);
                    src.indent--;
                    src.line("}");
                }
            }
            case DICT -> {
                String entry = src.fresh("entry");
                src.line("n += 4;");
                src.line("for (Map.Entry<String, " + box(type.elem) + "> " + entry + " : " + expr + ".entrySet()) {");
                src.indent++;
                src.line("n += 4 + Wire.utf8Length(" + entry + ".getKey());");
                sizeOf(src, type.elem, entry + ".getValue()", depth + 1);
                src.indent--;
                src.line("}");
            }
            default -> throw new IllegalArgumentException("cannot size " + type.kind);
        }
    }

    private static void writeOf(Src src, Schema type, String expr, int depth) {
        if (type.kind == Schema.Kind.OPT) {
            src.line("if (" + expr + " == null) {");
            src.indent++;
            src.line("out[o++] = 0;");
            src.indent--;
            src.line("} else {");
            src.indent++;
            src.line("out[o++] = 1;");
            writeOf(src, type.elem, expr, depth);
            src.indent--;
            src.line("}");
            return;
        }
        switch (type.kind) {
            case BOOL -> {
                src.line("out[o++] = (byte) (" + expr + " ? 1 : 0);");
            }
            case I8, U8 -> {
                src.line("Wire.putI8(out, o, " + expr + ");");
                src.line("o += 1;");
            }
            case I16, U16 -> {
                src.line("Wire.putI16(out, o, " + expr + ");");
                src.line("o += 2;");
            }
            case I32 -> src.line("o = Wire.putI32At(out, o, " + expr + ");");
            case U32 -> src.line("o = Wire.putU32At(out, o, " + expr + ");");
            case I64, INT, U64, UINT -> src.line("o = Wire.putI64At(out, o, " + expr + ");");
            case F32 -> src.line("o = Wire.putF32At(out, o, " + expr + ");");
            case F64 -> src.line("o = Wire.putF64At(out, o, " + expr + ");");
            case STR -> src.line("o = Wire.putStringAt(out, o, " + expr + ", Wire.DEFAULT_CAP);");
            case BYTES -> src.line("o = Wire.putRawAt(out, o, " + expr + ", 0, " + expr + ".length, Wire.DEFAULT_CAP);");
            case STRUCT -> src.line("o = " + expr + ".encodeTo(out, o);");
            case LIST -> {
                if (rawByteList(type)) {
                    src.line("o = Wire.putRawAt(out, o, " + expr + ", 0, " + expr + ".length, Wire.DEFAULT_CAP);");
                } else {
                    String item = src.fresh("item");
                    src.line("o = Wire.putU32At(out, o, " + expr + ".size());");
                    src.line("for (" + fieldType(type.elem) + " " + item + " : " + expr + ") {");
                    src.indent++;
                    writeOf(src, type.elem, item, depth + 1);
                    src.indent--;
                    src.line("}");
                }
            }
            case DICT -> {
                String keys = src.fresh("keys");
                String key = src.fresh("key");
                src.line("ArrayList<String> " + keys + " = new ArrayList<>(" + expr + ".keySet());");
                src.line(keys + ".sort(Wire::compareUtf8);");
                src.line("o = Wire.putU32At(out, o, " + keys + ".size());");
                src.line("for (String " + key + " : " + keys + ") {");
                src.indent++;
                src.line("o = Wire.putStringAt(out, o, " + key + ", Wire.DEFAULT_CAP);");
                writeOf(src, type.elem, expr + ".get(" + key + ")", depth + 1);
                src.indent--;
                src.line("}");
            }
            default -> throw new IllegalArgumentException("cannot write " + type.kind);
        }
    }

    private static void readOf(Src src, Schema type, String dest, int depth) {
        if (type.kind == Schema.Kind.OPT) {
            src.line("if (!in.opt()) {");
            src.indent++;
            src.line(dest + " = null;");
            src.indent--;
            src.line("} else {");
            src.indent++;
            readOf(src, type.elem, dest, depth);
            src.indent--;
            src.line("}");
            return;
        }
        switch (type.kind) {
            case BOOL -> src.line(dest + " = in.bool();");
            case I8 -> src.line(dest + " = (byte) in.i8();");
            case U8 -> src.line(dest + " = in.u8();");
            case I16 -> src.line(dest + " = (short) in.i16();");
            case U16 -> src.line(dest + " = in.u16();");
            case I32 -> src.line(dest + " = in.i32();");
            case U32 -> src.line(dest + " = in.u32();");
            case I64, INT, U64, UINT -> src.line(dest + " = in.i64();");
            case F32 -> src.line(dest + " = in.f32();");
            case F64 -> src.line(dest + " = in.f64();");
            case STR -> src.line(dest + " = in.str();");
            case BYTES -> src.line(dest + " = in.bytes().toArray();");
            case STRUCT -> src.line(dest + " = " + className(type.name) + ".decodeFrom(in);");
            case LIST -> {
                if (rawByteList(type)) {
                    String count = src.fresh("count");
                    src.line("int " + count + " = in.count(1);");
                    src.line(dest + " = new byte[" + count + "];");
                    src.line("System.arraycopy(in.b, in.p, " + dest + ", 0, " + count + ");");
                    src.line("in.p += " + count + ";");
                } else {
                    String count = src.fresh("count");
                    String list = src.fresh("list");
                    String item = src.fresh("item");
                    String index = src.fresh("i");
                    src.line("int " + count + " = in.count(" + type.elem.minSize() + ");");
                    src.line("ArrayList<" + box(type.elem) + "> " + list + " = new ArrayList<>(" + count + ");");
                    src.line("for (int " + index + " = 0; " + index + " < " + count + "; " + index + "++) {");
                    src.indent++;
                    src.line(box(type.elem) + " " + item + ";");
                    readOf(src, type.elem, item, depth + 1);
                    src.line(list + ".add(" + item + ");");
                    src.indent--;
                    src.line("}");
                    src.line(dest + " = " + list + ";");
                }
            }
            case DICT -> {
                String count = src.fresh("count");
                String map = src.fresh("map");
                String prev = src.fresh("prev");
                String key = src.fresh("key");
                String item = src.fresh("item");
                String index = src.fresh("i");
                int each = 4 + type.elem.minSize();
                src.line("int " + count + " = in.count(" + each + ");");
                src.line("LinkedHashMap<String, " + box(type.elem) + "> " + map + " = LinkedHashMap.newLinkedHashMap(" + count + ");");
                src.line("String " + prev + " = null;");
                src.line("for (int " + index + " = 0; " + index + " < " + count + "; " + index + "++) {");
                src.indent++;
                src.line("String " + key + " = in.str();");
                src.line("if (" + prev + " != null && Wire.compareUtf8(" + prev + ", " + key + ") >= 0) {");
                src.indent++;
                src.line("throw KilnException.type();");
                src.indent--;
                src.line("}");
                src.line(prev + " = " + key + ";");
                src.line(box(type.elem) + " " + item + ";");
                readOf(src, type.elem, item, depth + 1);
                src.line(map + ".put(" + key + ", " + item + ");");
                src.indent--;
                src.line("}");
                src.line(dest + " = " + map + ";");
            }
            default -> throw new IllegalArgumentException("cannot read " + type.kind);
        }
    }

    private static boolean rawByteList(Schema type) {
        return type.kind == Schema.Kind.LIST && (type.elem.kind == Schema.Kind.U8 || type.elem.kind == Schema.Kind.I8);
    }

    static String fieldType(Schema type) {
        if (type.kind == Schema.Kind.OPT) {
            return box(type.elem);
        }
        return switch (type.kind) {
            case BOOL -> "boolean";
            case I8 -> "byte";
            case I16 -> "short";
            case I32, U8, U16 -> "int";
            case I64, INT, U32, U64, UINT -> "long";
            case F32 -> "float";
            case F64 -> "double";
            case STR -> "String";
            case BYTES -> "byte[]";
            case LIST -> rawByteList(type) ? "byte[]" : "List<" + box(type.elem) + ">";
            case DICT -> "Map<String, " + box(type.elem) + ">";
            case STRUCT -> className(type.name);
            default -> throw new IllegalArgumentException(type.kind.name());
        };
    }

    private static String box(Schema type) {
        if (type.kind == Schema.Kind.OPT) {
            return box(type.elem);
        }
        return switch (type.kind) {
            case BOOL -> "Boolean";
            case I8 -> "Byte";
            case I16 -> "Short";
            case I32, U8, U16 -> "Integer";
            case I64, INT, U32, U64, UINT -> "Long";
            case F32 -> "Float";
            case F64 -> "Double";
            default -> fieldType(type);
        };
    }

    static String className(String name) {
        String ident = ident(name);
        if (ident.isEmpty()) {
            return "Root";
        }
        if (Character.isLowerCase(ident.charAt(0))) {
            return Character.toUpperCase(ident.charAt(0)) + ident.substring(1);
        }
        return ident;
    }

    static String fieldName(String name) {
        return ident(name);
    }

    static String ident(String name) {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < name.length(); i++) {
            char c = name.charAt(i);
            boolean ok = (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || c == '_';
            if (i > 0 && c >= '0' && c <= '9') {
                ok = true;
            }
            sb.append(ok ? c : '_');
        }
        if (sb.length() == 0) {
            return "value";
        }
        if (sb.charAt(0) >= '0' && sb.charAt(0) <= '9') {
            sb.insert(0, '_');
        }
        String out = sb.toString();
        if (KEYWORDS.contains(out)) {
            return out + "_";
        }
        return out;
    }

    private static final class Src {
        final StringBuilder sb = new StringBuilder();
        int indent;
        int seq;

        String fresh(String prefix) {
            return prefix + (seq++);
        }

        void line(String text) {
            if (!text.isEmpty()) {
                sb.append("    ".repeat(indent));
            }
            sb.append(text).append('\n');
        }
    }
}
